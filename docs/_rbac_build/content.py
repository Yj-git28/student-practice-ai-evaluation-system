# ============ 3 口径纠正 ============
H(1, "3　四项口径纠正")

P("通用 RBAC 教程里的 perm_key、user_role 中间表、权限类型、返回体写法，与本项目实库都不一致。照教程直接写，会在第三步和第四步反复返工，所以先在本章一次性统一。")

H(2, "3.1　perm_key 就是 perm_code")
P("实库字段名是 perm_code，实体类、Mapper、Redis 键值里统一用 permCode，全项目不要再出现 permKey 这个叫法。种子数据已给出 training:list、training:publish、training:submit、ai:list、evaluation:list、user:list、config:list 七个码，新增权限沿用模块:动作的两段式，全小写、冒号分隔。")

H(2, "3.2　没有 user_role 表，当前是单角色")
P("实库不存在 user_role，用户与角色的关系落在 sys_user.role_id 上，一个账号只能有一个角色。因此给用户分配角色不是往中间表插记录，而是一条 UPDATE sys_user SET role_id 的语句，写库动作与缓存失效都比多角色方案简单。若后续真要支持一人多角色（例如教师兼管理员），再新建 sys_user_role 表，并把 role_id 降级为主角色；这件事放到第七步扩展里做，不要提前改表，否则第 6 章的接口全部要重写。")

H(2, "3.3　perm_type 的取值与含义")
P("现有 7 条数据里 perm_type 只有 1 和 2：取值为 1 的都带 perm_path，如 /training、/ai-check、/evaluation、/system/user、/system/config；取值为 2 的都没有路径，如发布实训、提交作业。据此本文约定 1 为菜单类、2 为按钮类，并在第 5 章把它写成数据约束：菜单必须有 perm_path，按钮必须挂在某个菜单下。")

H(2, "3.4　返回体与 401、403")
